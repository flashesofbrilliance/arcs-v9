#!/usr/bin/env python3
"""jtbd_drift_report: weekly read-only drift report for the JTBD graph (row jtbd-graph-s5-feedback). Stdlib.

Rules: _PATTERNS/2026-10-20-jtbd-s5-preregistration.md, decision 4. Writes ONLY under _STATE/jtbd-graph/ (gitignored):
drift-<date>.md, drift-latest.md and drift-history.jsonl (one row per run, its own memory between weeks). It sends
nothing, opens no network connection and writes no database. Inputs: the generated graph
(_STATE/jtbd-graph/graph.json, scripts/universe_jtbd_adapter.py), the backlog, and the weights from
scripts/jtbd_edge_weights.py (recomputed here from the local receipt export).

Sections: new tools with no job · jobs blocked repeatedly · blockers older than 3 beats (1 beat = 1 day, as
scripts/pulse.py) · edges whose weights moved · demotion flags (for Zach, never applied) · coverage (test 1).

Weekly, Monday morning (a scheduled task only if Zach approves one; otherwise run by hand or from /loops):
  python3 scripts/universe_receipts_adapter.py --export && python3 scripts/jtbd_drift_report.py
  python3 scripts/jtbd_drift_report.py --self-test
"""
import argparse
import datetime as dt
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import jtbd_edge_weights as jew  # noqa: E402
import receipt_coverage as rc  # noqa: E402

OUT_DIR = "_STATE/jtbd-graph"
GRAPH = OUT_DIR + "/graph.json"
HISTORY = "drift-history.jsonl"
BEATS_OLD = 3
JOB_EDGES = ("serves", "needs")


def _safe_dir(root, out_dir):
    """The only legal output dir is <root>/_STATE/jtbd-graph. Anything else (incl. via .. or a symlink) raises."""
    want = os.path.realpath(os.path.join(root, OUT_DIR))
    got = os.path.realpath(os.path.join(root, out_dir))
    if got != want or want != os.path.join(os.path.realpath(root), OUT_DIR):
        raise ValueError(f"refusing to write outside {OUT_DIR}: {out_dir}")
    return got


def _history(d):
    p = os.path.join(d, HISTORY)
    rows = []
    if os.path.exists(p):
        for l in open(p, encoding="utf-8"):
            if l.strip():
                try:
                    rows.append(json.loads(l))
                except ValueError:
                    pass
    return rows


def snapshot(graph, rows, today):
    """Mechanical facts for one run."""
    atoms = {a["id"]: a for a in graph.get("atoms", [])}
    linked = set()
    for e in graph.get("edges", []):
        if e.get("type") in JOB_EDGES:
            for a, b in ((e["from"], e["to"]), (e["to"], e["from"])):
                if a.startswith("tool:") and b.startswith("job:"):
                    linked.add(a)
    tools_no_job = sorted(i for i in atoms if i.startswith("tool:") and i not in linked)
    byid = {"job:backlog:" + r["id"]: r for r in rows}
    blocked = sorted(j for j, r in byid.items() if r.get("state") == "BLOCKED")
    added = {j: byid[j].get("added") for j in blocked}
    return {"date": str(today), "tools": sorted(i for i in atoms if i.startswith("tool:")),
            "tools_no_job": tools_no_job, "blocked": blocked, "blocked_added": added}


def build(graph, rows, weights, history, today):
    snap = snapshot(graph, rows, today)
    prev = history[-1] if history else None
    prev_tools = set(prev["tools"]) if prev else None
    new_no_job = [t for t in snap["tools_no_job"] if prev_tools is not None and t not in prev_tools]
    seen_blocked = {}
    for h in history:
        for j in h.get("blocked", []):
            seen_blocked.setdefault(j, h["date"])
    repeat = [j for j in snap["blocked"] if j in seen_blocked]
    old = []
    for j in snap["blocked"]:
        cands = [str(x)[:10] for x in (seen_blocked.get(j), snap["blocked_added"].get(j)) if x]
        first = min(cands) if cands else None   # earliest of first sighting and the row's added date
        try:
            age = (today - dt.date.fromisoformat(str(first)[:10])).days
        except ValueError:
            age = None
        if age is not None and age > BEATS_OLD:
            old.append((j, first, age))
    prev_w = (prev or {}).get("weights", {})
    moved = sorted((k, prev_w.get(k, 1.0), v) for k, v in weights["weights"].items() if prev_w.get(k, 1.0) != v)
    moved += sorted((k, v, 1.0) for k, v in prev_w.items() if k not in weights["weights"])
    snap["weights"] = weights["weights"]
    return snap, {"first_run": prev is None, "tools_no_job_total": len(snap["tools_no_job"]), "new_no_job": new_no_job,
                  "repeat_blocked": repeat, "old_blockers": old, "moved": moved,
                  "flags": weights["demotion_flags"], "coverage": weights["coverage"], "start": weights.get("start"),
                  "note": weights.get("note")}


def render(rep, today):
    L = [f"# JTBD drift report, {today}", "",
         "Read-only. Generated by `scripts/jtbd_drift_report.py`; rules in `_PATTERNS/2026-10-20-jtbd-s5-preregistration.md`.",
         "Nothing here was sent or applied. Demotion flags wait for Zach.", ""]
    c = rep["coverage"]
    L.append(f"## Coverage (test 1: at least 70% within 14 days of start)")
    L.append(f"- start: {rep['start'] or 'not set (nothing counted yet; set after merge)'}")
    L.append(f"- receipts since start: {c['receipts_since_start']}, with job_id and tool_id: {c['with_job_and_tool']}"
             + (f" ({c['share']:.0%})" if c["share"] is not None else ""))
    for m in rep.get("coverage_missing", []):
        L.append(f"  - lacks {'+'.join(m['lacks'])}: {m['receipt_id']}")
    L.append("- one command for the 2026-11-03 check: `python3 scripts/receipt_coverage.py --export`")
    if rep["note"]:
        L.append(f"- {rep['note']}")
    L += ["", "## New tools with no job"]
    if rep["first_run"]:
        L.append(f"- first run: baseline of {rep['tools_no_job_total']} tools with no job recorded; new ones show from next week.")
    L += [f"- {t}" for t in rep["new_no_job"]] or ([] if rep["first_run"] else ["- none"])
    L += ["", "## Jobs blocked repeatedly (blocked now and in an earlier report)"]
    L += [f"- {j}" for j in rep["repeat_blocked"]] or ["- none"]
    L += ["", f"## Blockers older than {BEATS_OLD} beats (1 beat = 1 day)"]
    L += [f"- {j}: {age} beats (since {first})" for j, first, age in rep["old_blockers"]] or ["- none"]
    L += ["", "## Edges whose weights moved since the last report"]
    L += [f"- {k}: {a} -> {b}" for k, a, b in rep["moved"]] or ["- none"]
    L += ["", "## Demotion flags (computed below 1.0; NOT applied; Zach decides)"]
    L += [f"- {f['edge']}: computed {f['computed']} over {f['uses']} uses" for f in rep["flags"]] or ["- none"]
    L += ["", "## Usefulness (test 3)", "- If two consecutive reports lead to no action Zach takes, cut this report to monthly.", ""]
    return "\n".join(L)


def run(root=REPO, out_dir=OUT_DIR, today=None, graph=None, quiet=False):
    d = _safe_dir(root, out_dir)
    today = today or dt.date.today()
    if type(today) is not dt.date:
        raise ValueError(f"today must be a datetime.date, got {type(today).__name__}")
    for name in (f"drift-{today}.md", "drift-latest.md", HISTORY):
        if os.path.islink(os.path.join(d, name)):
            raise ValueError(f"refusing to write through a symlink: {OUT_DIR}/{name}")
    if graph is None:
        gp = os.path.join(root, GRAPH)
        if not os.path.exists(gp):
            raise SystemExit("no graph: run `python3 scripts/universe_jtbd_adapter.py` first")
        graph = json.load(open(gp, encoding="utf-8"))
    rows = [json.loads(l) for l in open(os.path.join(root, jew.BACKLOG), encoding="utf-8") if l.strip()]
    cfg = jew.load_config(root)
    rec = jew.load_export(root)
    weights = jew.compute(rec or [], jew.backlog_states(root), cfg)
    if rec is None:
        weights["note"] = "no receipt export; run `python3 scripts/universe_receipts_adapter.py --export`"
    hist = _history(d)
    snap, rep = build(graph, rows, weights, hist, today)
    rep["coverage_missing"] = rc.coverage(rec or [], jew._ts(cfg.get("start")))["missing"]
    text = render(rep, today)
    os.makedirs(d, exist_ok=True)
    for name in (f"drift-{today}.md", "drift-latest.md"):
        with jew.open_nofollow(os.path.join(d, name), "w") as f:
            f.write(text)
    with jew.open_nofollow(os.path.join(d, HISTORY), "a") as f:
        f.write(json.dumps(snap) + "\n")
    if not quiet:
        print(f"jtbd drift: {os.path.relpath(os.path.join(d, 'drift-latest.md'), root)} · new tools with no job {len(rep['new_no_job'])} · "
              f"repeat-blocked {len(rep['repeat_blocked'])} · old blockers {len(rep['old_blockers'])} · moved {len(rep['moved'])} · "
              f"flags {len(rep['flags'])}")
    return rep


def latest_link(root=REPO):
    """For /loops: (path, date) of the latest report, or None."""
    p = os.path.join(root, OUT_DIR, "drift-latest.md")
    if not os.path.exists(p):
        return None
    first = open(p, encoding="utf-8").readline().strip()
    return os.path.relpath(p, root), first.rsplit(" ", 1)[-1]


def self_test():
    ok = True

    def check(name, cond):
        nonlocal ok
        print(("PASS " if cond else "FAIL ") + name)
        ok &= bool(cond)

    with tempfile.TemporaryDirectory() as root:
        os.makedirs(os.path.join(root, "_QUEUE")); os.makedirs(os.path.join(root, "runtime/specs/jtbd-s5"))
        json.dump({"start": None, "n_min": 3, "alpha": 0.1, "promote_days": 30}, open(os.path.join(root, jew.CONFIG), "w"))
        open(os.path.join(root, jew.BACKLOG), "w").write(
            json.dumps({"id": "b1", "state": "BLOCKED", "added": "2026-10-01"}) + "\n" + json.dumps({"id": "j1", "state": "OPEN"}) + "\n")
        g = {"atoms": [{"id": "tool:script:a.py"}, {"id": "tool:script:b.py"}, {"id": "job:backlog:j1"}],
             "edges": [{"from": "tool:script:a.py", "to": "job:backlog:j1", "type": "serves"}]}
        before = set()
        for dp, _, fs in os.walk(root):
            before |= {os.path.join(dp, f) for f in fs}
        r1 = run(root, today=dt.date(2026, 10, 26), graph=g, quiet=True)
        check("first run: baseline, no 'new' tools claimed", r1["first_run"] and r1["new_no_job"] == [] and r1["tools_no_job_total"] == 1)
        check("blocker older than 3 beats is listed", [x[0] for x in r1["old_blockers"]] == ["job:backlog:b1"])
        g["atoms"].append({"id": "tool:script:c.py"})
        r2 = run(root, today=dt.date(2026, 11, 2), graph=g, quiet=True)
        check("second run: the new orphan tool is listed", r2["new_no_job"] == ["tool:script:c.py"])
        check("second run: the blocked job is repeat-blocked", r2["repeat_blocked"] == ["job:backlog:b1"])
        after = set()
        for dp, _, fs in os.walk(root):
            after |= {os.path.join(dp, f) for f in fs}
        new = {os.path.relpath(p, root) for p in after - before}
        check("writes only under _STATE/jtbd-graph/", new and all(p.startswith(OUT_DIR + "/") for p in new))
        for bad in ("_STATE", "_STATE/jtbd-graph/../../x", "/tmp", "public"):
            try:
                run(root, out_dir=bad, graph=g, quiet=True); refused = False
            except ValueError:
                refused = True
            check(f"refuses out_dir {bad!r}", refused)
        os.symlink("/tmp", os.path.join(root, "_STATE/link"))
        try:
            _safe_dir(root, "_STATE/link"); refused = False
        except ValueError:
            refused = True
        check("refuses a symlinked out_dir", refused)
        os.makedirs(os.path.join(root, "elsewhere"))
        os.rename(os.path.join(root, OUT_DIR), os.path.join(root, "elsewhere/jg"))
        os.symlink(os.path.join(root, "elsewhere/jg"), os.path.join(root, OUT_DIR))
        try:
            _safe_dir(root, OUT_DIR); refused = False
        except ValueError:
            refused = True
        check("refuses when _STATE/jtbd-graph itself is a symlink", refused)
        os.remove(os.path.join(root, OUT_DIR)); os.rename(os.path.join(root, "elsewhere/jg"), os.path.join(root, OUT_DIR))
        for name in ("drift-latest.md", HISTORY):
            tgt = os.path.join(root, OUT_DIR, name); keep = tgt + ".keep"; os.rename(tgt, keep)
            os.symlink(os.path.join(root, "outside.txt"), tgt)
            try:
                run(root, today=dt.date(2026, 11, 9), graph=g, quiet=True); refused = False
            except ValueError:
                refused = True
            check(f"refuses to write {name} through a symlink", refused and not os.path.exists(os.path.join(root, "outside.txt")))
            os.remove(tgt); os.rename(keep, tgt)
        for bad_today in ("../../escaped", dt.datetime(2026, 11, 9)):
            try:
                run(root, today=bad_today, graph=g, quiet=True); refused = False
            except ValueError:
                refused = True
            check(f"refuses today={bad_today!r}", refused)
        txt = open(os.path.join(root, OUT_DIR, "drift-latest.md")).read()
        check("report says nothing was sent or applied", "Nothing here was sent or applied" in txt)
        check("latest_link reads the date", latest_link(root) == (OUT_DIR + "/drift-latest.md", "2026-11-02"))
    print("self-test:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description="Weekly JTBD drift report (read-only; writes only _STATE/jtbd-graph/).")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    run()
    return 0


if __name__ == "__main__":
    sys.exit(main())
