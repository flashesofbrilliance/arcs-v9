#!/usr/bin/env python3
"""gate_chain_build: kit organism 72 (week strip and chains) and the hardening section of status.arcs.care/gauntlets.

The story: each week, how many gates entered the always-run path, and for each fix that added one, the chain
break -> repair -> gate. Every point is read from git, never typed:

  gates      a script first named in scripts/git-hooks/pre-commit, dated by the commit that added that line
  chains     a `fix(...)` commit that first wired a gate: its subject is the break it fixed, its sha the repair,
             the script it wired the gate (16 of them through 2026-11-12)
  reversals  _STATE/falsification-ledger.jsonl rows by week, public shape only (id and scope; claim text stays internal)

History is pinned: the JSON records `through`, the last hook commit it read, so --check rebuilds from that commit and
never goes stale because a later commit touched the hook. A plain write moves `through` to the newest hook commit.

Air-gap (the page is public): commit text carries client and counterpart names and internal jargon, so it never
reaches the page. Each chain's public words come from PUBLIC: a reviewed plain-language break and repair, written from
that commit's own message, or None to withhold the chain (counted, not shown). A chain with no PUBLIC entry fails the
build, so a new chain cannot ship unread. SCRUB rewrites client words in scopes and gate names, and a scope outside
REVIEWED_SCOPES fails the build too. The full gate list and raw subjects stay in runtime/specs/gate-chains.json, which
is not served; the public fragment carries counts, reviewed chains and reversal ids only.

In:  git history of scripts/git-hooks/pre-commit; _STATE/falsification-ledger.jsonl; src/ui-kit/week-strip/*.css,*.js
Out: runtime/specs/gate-chains.json                     the cited table (internal)
     src/ui-kit/specimens/week-strip.json -> kit_specimen.py -> src/ui-kit/recoil-report/72-week-strip.html
     src/ui-kit/week-strip/gauntlet-fragment.html       style + no-JS floor + data + script
     scripts/gauntlet_log_public_template.html          the fragment, between its week-strip sentinels
     then scripts/gauntlet_log_emit.py rewrites public/gauntlet-log.html

  python3 scripts/gate_chain_build.py              read history to the newest hook commit and write everything
  python3 scripts/gate_chain_build.py --check      exit 1 if any output differs from a rebuild at the pinned commit
  python3 scripts/gate_chain_build.py --preview P  the fragment under the kit tokens as a page, for page_gate
  python3 scripts/gate_chain_build.py --self-test
Stdlib only.
"""
