def outputs(through):
    t = table(through)
    p = payload(t)
    frag = fragment(p)
    return {TABLE: json.dumps(t, indent=1, ensure_ascii=False) + "\n",
            SPEC: json.dumps(spec(p), indent=1, ensure_ascii=False) + "\n",
            FRAG: frag, TPL: template(frag)}, t, p


def pinned():
    return json.load(open(TABLE, encoding="utf-8"))["through"]


def self_test():
    outs, t, p = outputs(pinned())
    for w in t["weeks"]:
        for c in w["chains"]:
            subprocess.run(["git", "cat-file", "-e", c["sha"] + "^{commit}"], cwd=ROOT, check=True)
    pub = outs[FRAG]
    for pat, _ in SCRUB[:1]:
        assert not re.search(pat, pub, re.I), "scrub term %s in the public fragment" % pat
    assert "claim" not in pub, "belief claim text in the fragment"
    for w in t["weeks"]:
        for c in w["chains"]:
            raw = c["subject"].split(":", 1)[1].strip()
            assert raw not in pub, "raw commit subject reached the public fragment: %s" % c["sha"]
    assert "e88ca1da" not in pub, "withheld chain on the page"
    assert "—" not in pub and "—" not in outs[SPEC], "em-dash"
    assert sum(len(w["gates"]) for w in t["weeks"]) == t["gate_count"], "gate counts do not add up"
    assert "<li>" in floor(p), "empty no-JS floor"
    saved = dict(REVIEWED_SCOPES)
    REVIEWED_SCOPES.pop("db")
    try:
        table(t["through"])
        raise AssertionError("an unreviewed scope did not fail")
    except SystemExit:
        pass
    finally:
        REVIEWED_SCOPES.update(saved)
    print("gate_chain_build self-test: OK (%d weeks, %d gates, %d chains)" % (len(t["weeks"]), t["gate_count"], t["chain_count"]))
    return 0


def main():
    if "--self-test" in sys.argv:
        return self_test()
    if "--check" in sys.argv:
        outs, _, _ = outputs(pinned())
        stale = [os.path.relpath(f, ROOT) for f, s in outs.items() if not os.path.exists(f) or open(f, encoding="utf-8").read() != s]
        if stale:
            print("✖ stale: %s. fix: python3 scripts/gate_chain_build.py" % ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    if "--preview" in sys.argv:
        outs, _, _ = outputs(pinned())
        path = sys.argv[sys.argv.index("--preview") + 1]
        open(path, "w", encoding="utf-8").write(preview(outs[FRAG]))
        print("wrote", path)
        return 0
    through = git("log", "-1", "--format=%H", "HEAD", "--", HOOK).strip()
    outs, t, _ = outputs(through)
    for f, s in outs.items():
        os.makedirs(os.path.dirname(f), exist_ok=True)
        open(f, "w", encoding="utf-8").write(s)
        print("wrote", os.path.relpath(f, ROOT))
    rc = subprocess.call([sys.executable, os.path.join(ROOT, "scripts/kit_specimen.py"), SPEC])
    return rc or subprocess.call([sys.executable, os.path.join(ROOT, "scripts/gauntlet_log_emit.py")], cwd=ROOT)


if __name__ == "__main__":
    sys.exit(main())
