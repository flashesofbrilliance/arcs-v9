#!/usr/bin/env python3
"""kit_job_ratchet.py: the count of kit parts that name a backlog job may rise, never fall.

Reads src/ui-kit/kit-manifest.json (generated by scripts/kit_pull.py, never hand-edited) and compares the
number of parts with at least one job against the floor in runtime/specs/kit-job-coverage-floor.json.

    python3 scripts/kit_job_ratchet.py            check (exit 1 if the count fell below the floor)
    python3 scripts/kit_job_ratchet.py --bump     raise the floor to the current count
    python3 scripts/kit_job_ratchet.py --self-test
Stdlib only.
"""
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "src/ui-kit/kit-manifest.json"
FLOOR = ROOT / "runtime/specs/kit-job-coverage-floor.json"


def count(manifest):
    parts = manifest["parts"]
    return sum(1 for p in parts if p.get("jobs")), len(parts)


def check(manifest, floor):
    have, total = count(manifest)
    return have >= floor, have, total


def main(argv):
    if "--self-test" in argv:
        return self_test()
    manifest = json.loads(MANIFEST.read_text())
    have, total = count(manifest)
    if "--bump" in argv:
        FLOOR.write_text(json.dumps({"parts_naming_a_job": have, "of": total}, indent=2) + "\n")
        print(f"floor raised to {have} of {total}")
        return 0
    floor = json.loads(FLOOR.read_text())["parts_naming_a_job"]
    ok, have, total = check(manifest, floor)
    if not ok:
        print(f"kit job coverage fell: {have} of {total} parts name a job, floor is {floor}. "
              "Name the job in a backlog row (part id in route/jtbd) or restore the row, then rerun "
              "python3 scripts/kit_pull.py manifest.", file=sys.stderr)
        return 1
    note = f" (floor {floor}; run --bump to ratchet up)" if have > floor else ""
    print(f"kit job coverage ok: {have} of {total} parts name a job{note}")
    return 0


def self_test():
    good = {"parts": [{"jobs": ["a"]}, {"jobs": ["b"]}, {"jobs": []}]}
    bad = {"parts": [{"jobs": ["a"]}, {"jobs": []}, {"jobs": []}]}
    assert check(good, 2)[0], "good must pass"
    assert not check(bad, 2)[0], "bad must fail"
    assert check(good, 1)[0], "raise above floor passes"
    print("kit_job_ratchet self-test ok (fails on bad, passes on good)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
