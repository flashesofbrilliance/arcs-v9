#!/usr/bin/env node
// resume_static_emit: give resume.arcs.care a text copy that readers without JavaScript can see.
//
// Why (2026-10-30): public/resume.html is a React app compiled in the browser, so a crawler or an
// AI recruiter tool that does not run JavaScript sees only the <title>. This renders the page's default
// view in a headless browser and writes that text to:
//   1. a <noscript> block in public/resume.html, between the RESUME-STATIC sentinels
//   2. public/resume-index.txt, served as Markdown at resume.arcs.care/index.md
// The text is generated from the page, never hand-written, so it cannot say more than the page does.
//
// Usage:
//   node scripts/resume_static_emit.mjs           # regenerate both
//   node scripts/resume_static_emit.mjs --check   # exit 1 if either is stale
import { chromium } from 'playwright';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const PAGE = 'public/resume.html';
const TXT = 'public/resume-index.txt';
const START = '<!-- RESUME-STATIC:START (generated by scripts/resume_static_emit.mjs; do not edit) -->';
const END = '<!-- RESUME-STATIC:END -->';
const check = process.argv.includes('--check');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

async function renderLines() {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  await page.goto(pathToFileURL(resolve(PAGE)).href);
  await page.waitForSelector('.page', { timeout: 20000 });
  await page.waitForTimeout(1500);
  const clean = (txt) => txt.split('\n').map((l) => l.replace(/\s+/g, ' ').trim()).filter((l) => /[A-Za-z0-9$<]/.test(l));
  const grab = () => page.$eval('.page', (el) => el.innerText).then(clean);
  // Sections open one at a time (accordion), so open each in turn and merge every capture in
  // page order: a line not seen yet goes in right after the line that preceded it.
  const merged = await grab();
  const toggles = await page.evaluate(() =>
    [...document.querySelectorAll('.page *')].filter((e) => e.childElementCount === 0 && /^[▼▲]$/.test(e.textContent.trim())).length);
  for (let k = 0; k < toggles; k++) {
    const opened = await page.evaluate((k) => {
      const hits = [...document.querySelectorAll('.page *')].filter((e) => e.childElementCount === 0 && /^[▼▲]$/.test(e.textContent.trim()));
      if (!hits[k] || hits[k].textContent.trim() !== '▼') return false;
      hits[k].parentElement.click();
      return true;
    }, k);
    if (!opened) continue;
    await page.waitForTimeout(400);
    let prev = -1;
    for (const l of await grab()) {
      const at = merged.indexOf(l, prev + 1);
      if (at >= 0) { prev = at; continue; }
      if (merged.includes(l)) continue;
      merged.splice(prev + 1, 0, l); prev += 1;
    }
  }
  const text = merged.join('\n');
  await browser.close();
  const skip = /^(SKETCH|WIREFRAME|PIXEL PERFECT|FULL|RESUME|▲ collapse|▾.*|◈ BOOK 30 MIN|→ run through compass)$/;
  return text.split('\n').map((l) => l.replace(/\s+/g, ' ').replace(/ ?— ?/g, ', ').trim()).filter((l) => /[A-Za-z0-9$<]/.test(l) && !skip.test(l));
}

const lines = await renderLines();
const md = `# ${lines[0]}\n\n` + lines.slice(1).map((l) => `- ${l}`).join('\n') +
  '\n\nAgent-readable profile with sourced, dated facts: https://zach.md\n';
const block = `${START}\n<noscript><main style="--measure:680px;max-width:var(--measure);margin:0 auto;padding:24px 16px;font-family:system-ui,sans-serif;line-height:1.55">\n<h1>${esc(lines[0])}</h1>\n` +
  lines.slice(1).map((l) => `<p>${esc(l)}</p>`).join('\n') +
  `\n<p>Agent-readable profile: <a href="https://zach.md">zach.md</a></p>\n</main></noscript>\n${END}`;

let html = readFileSync(PAGE, 'utf8');
const i = html.indexOf(START), j = html.indexOf(END);
const next = i >= 0 && j > i
  ? html.slice(0, i) + block + html.slice(j + END.length)
  : html.replace('<div id="root"></div>', `<div id="root"></div>\n${block}`);

if (check) {
  let txt = '';
  try { txt = readFileSync(TXT, 'utf8'); } catch {}
  if (next !== html || txt !== md) {
    console.error('resume_static_emit: stale. Run: node scripts/resume_static_emit.mjs');
    process.exit(1);
  }
  console.log(`resume_static_emit: current (${lines.length} lines)`);
} else {
  writeFileSync(PAGE, next);
  writeFileSync(TXT, md);
  console.log(`resume_static_emit: wrote ${lines.length} lines to ${PAGE} <noscript> and ${TXT}`);
}
