#!/usr/bin/env python3
"""kit_gate_results.py: store, per kit part and per page, whether the pages that use the part pass page_gate.

Reads src/ui-kit/kit-manifest.json (which pages use which parts, which fidelity states a part renders), runs
page_gate.py --static on each distinct page, and writes src/ui-kit/kit-gate-results.json (generated, never
hand-edited). The ranker uses it as the tie-breaker after shape coverage, fidelity gaps and job links.

    python3 scripts/kit_gate_results.py            regenerate the results file
    python3 scripts/kit_gate_results.py --show     print a summary, write nothing
    python3 scripts/kit_gate_results.py --self-test
Static checks only (doctype, charset, viewport, mojibake, wrap lint); render checks need a browser and are not
stored here. A page that is missing records pass=null (unknown), never pass=true. Stdlib only.
"""
import json
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "src/ui-kit/kit-manifest.json"
OUT = ROOT / "src/ui-kit/kit-gate-results.json"
ERR = re.compile(r"^\s+ERROR (\S+?):", re.M)


def gate_page(path):
    if not (ROOT / path).is_file():
        return {"pass": None, "errors": ["missing"]}
    r = subprocess.run([sys.executable, str(ROOT / "scripts/page_gate.py"), "--static", path],
                       capture_output=True, text=True, cwd=ROOT)
    errs = sorted(set(ERR.findall(r.stdout + r.stderr)))
    return {"pass": r.returncode == 0, "errors": errs}


def per_part(manifest, pages):
    out = {}
    for p in manifest["parts"]:
        used = sorted(p.get("pages", []))
        res = [pages[u]["pass"] for u in used if u in pages]
        known = [x for x in res if x is not None]
        out[p["id"]] = {
            "pages_used": len(used),
            "pages_passed": sum(1 for x in known if x),
            "pages_failed": sum(1 for x in known if not x),
            "pass_rate": round(sum(1 for x in known if x) / len(known), 3) if known else None,
            "fidelity_declared": p.get("fidelity", []),
            "failing_pages": [u for u in used if u in pages and pages[u]["pass"] is False],
        }
    return out


def build():
    manifest = json.loads(MANIFEST.read_text())
    paths = sorted({u for p in manifest["parts"] for u in p.get("pages", [])})
    with ThreadPoolExecutor(max_workers=8) as ex:
        pages = dict(zip(paths, ex.map(gate_page, paths)))
    return {"_comment": "Generated by scripts/kit_gate_results.py. Static page_gate only. Do not hand-edit.",
            "gate": "page_gate.py --static", "pages": pages, "parts": per_part(manifest, pages)}


def self_test():
    m = {"parts": [{"id": "a", "pages": ["x", "y"], "fidelity": ["sharp"]}, {"id": "b", "pages": ["y"]},
                   {"id": "c", "pages": []}, {"id": "d", "pages": ["z"]}]}
    pages = {"x": {"pass": True, "errors": []}, "y": {"pass": False, "errors": ["doctype"]},
             "z": {"pass": None, "errors": ["missing"]}}
    r = per_part(m, pages)
    assert r["a"]["pass_rate"] == 0.5 and r["a"]["failing_pages"] == ["y"]
    assert r["b"]["pass_rate"] == 0.0
    assert r["c"]["pass_rate"] is None and r["d"]["pass_rate"] is None, "unknown stays unknown"
    assert gate_page("does/not/exist.html") == {"pass": None, "errors": ["missing"]}
    print("kit_gate_results self-test ok")
    return 0


def main(argv):
    if "--self-test" in argv:
        return self_test()
    data = build()
    pg = data["pages"]
    ok = sum(1 for v in pg.values() if v["pass"])
    bad = sum(1 for v in pg.values() if v["pass"] is False)
    unk = sum(1 for v in pg.values() if v["pass"] is None)
    print(f"{len(pg)} pages: {ok} pass, {bad} fail, {unk} unknown")
    if "--show" not in argv:
        OUT.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")
        print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
