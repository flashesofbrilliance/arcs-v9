#!/usr/bin/env python3
"""grammar_chips_emit: write the chip grammar from runtime/specs/grammar-chips.json into
  - src/ui/grammarChipTokens.ts (the JSX tokens), and
  - the CSS block between the GRAMMAR-CHIPS sentinels in src/ui-kit/grammar-chips/chips.html.

Usage: python3 scripts/grammar_chips_emit.py [--check]
--check exits 1 when either output is out of date, or when the spec breaks a rule (never writes):
  dark tones equal their kit token in _tokens.css; every tone meets its contrast floor (light 4.6:1 on
  the darkest paper surface, dark 4.5:1 on the panel); no glyph is used twice; the three status glyphs
  match public/proof.html (shown, on request, not yet).
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "runtime/specs/grammar-chips.json"
TS = ROOT / "src/ui/grammarChipTokens.ts"
HTML = ROOT / "src/ui-kit/grammar-chips/chips.html"
START, END = "/* GRAMMAR-CHIPS:BEGIN generated by scripts/grammar_chips_emit.py; edit the spec, not this block */", "/* GRAMMAR-CHIPS:END */"


def mode_vars(spec, mode):
    m = dict(spec["modes"][mode])
    kv = m.get("kitVars", {})
    for key, var in kv.items():
        m[key] = f"var({var})"
    dp = spec["modes"][mode]["depth"]
    ins = spec["instrument"][mode]
    out = [f"--g-key:{ins['keyFace']};--g-highlight:{ins['highlight']};--g-lip:{ins['lip']};"]
    out += [f"--g-well:{dp['well']};--g-face:{dp['face']};--g-glass:{dp['glass']};--g-bevel:{dp['bevel']};--g-underlit:{dp['underlit']};"]
    out += [f"--g-bg:{m['bg']};--g-panel:{m['panel']};--g-elevated:{m['elevated']};--g-border:{m['border']};"
           f"--g-text:{m['text']};--g-text-2:{m['textSecondary']};--g-focus:{m['focus']};"
           f"--g-tint:{m['tint']};--g-edge:{m['edge']};"]
    for name, t in spec["tones"].items():
        out.append(f"--g-{name}:{'var(' + t['kitVar'] + ')' if kv else t[mode]};")
    return "".join(out)


