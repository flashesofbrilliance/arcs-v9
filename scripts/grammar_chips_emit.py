#!/usr/bin/env python3
"""grammar_chips_emit: write the chip grammar from runtime/specs/grammar-chips.json into
  - src/ui/grammarChipTokens.ts (the JSX tokens), and
  - the CSS block between the GRAMMAR-CHIPS sentinels in src/ui-kit/grammar-chips/chips.html.

Usage: python3 scripts/grammar_chips_emit.py [--check]
--check exits 1 when either output is out of date (never writes).
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "runtime/specs/grammar-chips.json"
TS = ROOT / "src/ui/grammarChipTokens.ts"
HTML = ROOT / "src/ui-kit/grammar-chips/chips.html"
START, END = "/* GRAMMAR-CHIPS:BEGIN generated by scripts/grammar_chips_emit.py; edit the spec, not this block */", "/* GRAMMAR-CHIPS:END */"


def mode_vars(spec, mode):
    m = dict(spec["modes"][mode])
    kv = m.get("kitVars", {})
    for key, var in kv.items():
        m[key] = f"var({var})"
    out = [f"--g-bg:{m['bg']};--g-panel:{m['panel']};--g-elevated:{m['elevated']};--g-border:{m['border']};"
           f"--g-text:{m['text']};--g-text-2:{m['textSecondary']};--g-focus:{m['focus']};"
           f"--g-tint:{m['tint']};--g-edge:{m['edge']};"]
    for name, t in spec["tones"].items():
        out.append(f"--g-{name}:{'var(' + t['kitVar'] + ')' if kv else t[mode]};")
    return "".join(out)


def css(spec):
    s, f = spec["shape"], spec["fonts"]
    dark, light = mode_vars(spec, "dark"), mode_vars(spec, "light")
    lines = [
        START,
        (ROOT / "src/ui-kit/recoil-report/_tokens.css").read_text().rstrip(),
        f":root{{{dark}color-scheme:dark}}",
        f"@media (prefers-color-scheme: light){{:root:not([data-theme=\"dark\"]){{{light}color-scheme:light}}}}",
        f":root[data-theme=\"light\"]{{{light}color-scheme:light}}",
        f":root[data-theme=\"dark\"]{{{dark}color-scheme:dark}}",
        f".g-chip{{--c:var(--g-neutral);display:inline-flex;align-items:center;gap:{s['gap']};padding:{s['padY']} {s['padX']};"
        f"border-radius:{s['radius']};border:1px solid color-mix(in srgb,var(--c) var(--g-edge),transparent);"
        f"background:color-mix(in srgb,var(--c) var(--g-tint),var(--g-panel));color:var(--g-text);"
        f"font:400 {s['bodySize']}/1.3 {f['sans']};white-space:nowrap;max-width:100%}}",
        f".g-chip .g-glyph{{color:var(--c);font-size:1em;line-height:1}}",
        f".g-chip .g-tag{{color:var(--c);font:700 {s['tagSize']}/1 {f['mono']};letter-spacing:.12em;text-transform:uppercase}}",
        ".g-chip .g-body{white-space:normal}",
    ]
    for name in spec["tones"]:
        lines.append(f".g-chip[data-tone=\"{name}\"]{{--c:var(--g-{name})}}")
    for name, fd in spec["fidelity"].items():
        rule = f".g-chip[data-fidelity=\"{name}\"] .g-body{{font-weight:{fd['weight']};letter-spacing:{fd['tracking']}}}"
        if fd["texture"] == "speckle":
            rule += (f".g-chip[data-fidelity=\"{name}\"]{{background-image:radial-gradient(color-mix(in srgb,var(--c) 30%,transparent) .6px,transparent .8px);"
                     "background-size:5px 5px}")
        if fd["texture"] == "interference":
                        rule += (f".g-chip[data-fidelity=\"{name}\"]{{background-image:radial-gradient(color-mix(in srgb,var(--g-say) 28%,transparent) .6px,transparent .8px),"
                     "radial-gradient(color-mix(in srgb,var(--g-limit) 24%,transparent) .6px,transparent .8px);background-size:4px 4px,4.6px 4.6px}")
        lines.append(rule)
    lines.append(".g-chip:focus-visible{outline:1px solid var(--g-focus);outline-offset:2px}")
    lines.append(END)
    return "\n".join(lines)


def ts(spec):
    body = json.dumps({k: spec[k] for k in ("version", "tones", "modes", "fidelity", "shape", "fonts")}, indent=2, ensure_ascii=False)
    return ("// Generated by scripts/grammar_chips_emit.py from runtime/specs/grammar-chips.json. Do not edit by hand.\n"
            f"export const grammarChips = {body} as const\n\n"
            "export type GrammarTone = keyof typeof grammarChips.tones\n"
            "export type GrammarFidelity = keyof typeof grammarChips.fidelity\n"
            "export type GrammarMode = keyof typeof grammarChips.modes\n")


def main():
    check = "--check" in sys.argv
    spec = json.loads(SPEC.read_text())
    want_ts = ts(spec)
    html = HTML.read_text()
    block = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not block.search(html):
        sys.exit(f"sentinels missing in {HTML}")
    want_html = block.sub(lambda _: css(spec), html)
    stale = [p for p, want in ((TS, want_ts), (HTML, want_html)) if not p.exists() or p.read_text() != want]
    if check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run python3 scripts/grammar_chips_emit.py)")
        sys.exit(1 if stale else 0)
    TS.write_text(want_ts)
    HTML.write_text(want_html)
    print("wrote", TS.relative_to(ROOT), "and", HTML.relative_to(ROOT))


if __name__ == "__main__":
    main()
