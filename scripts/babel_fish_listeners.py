#!/usr/bin/env python3
"""Write Babel Fish's listener registry into its artifact page, from the repo's own registries.

Never hand-type a listener list (AGENTS.md gotcha 16): each family is read from its source.
  archetype  operators/arcs_lte.py ARCHETYPE_REGISTRY (read with ast, nothing imported)
  operator   operators/OPERATOR-REGISTRY.json
  primitive  CLAUDE.md "ROM Primitives" list
  advisor    .claude/agents/{chief-*,idea-*,grug,scenario-runner}.md front matter
The six codex personas stay hand-mapped in the page (PERSONAS), from the imported codex.
No registry of protocols exists; the page says so instead of inventing one.

Usage: python3 scripts/babel_fish_listeners.py [--check]
  --check  exit 1 if the page's registry block is stale (writes nothing).
"""
import ast, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "runtime/specs/babel-fish/babel-fish-artifact.html"
BEGIN, END = "/* REGISTRY:BEGIN generated by scripts/babel_fish_listeners.py, do not edit */", "/* REGISTRY:END */"


def archetypes():
    tree = ast.parse((ROOT / "operators/arcs_lte.py").read_text())
    for node in ast.walk(tree):
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == "ARCHETYPE_REGISTRY":
            out = []
            for key, call in zip(node.value.keys, node.value.values):
                kw = {k.arg: ast.literal_eval(k.value) for k in call.keywords}
                out.append({"id": "arch-" + key.value.lower(), "family": "archetype", "kind": "audience",
                            "name": kw["name"], "dialect": ", ".join(kw["value_anchors"]),
                            "entry": "Trust builders: " + "; ".join(kw["trust_builders"]),
                            "revealed": "; ".join(kw["belief_states"]), "avoid": ", ".join(kw["forbidden_vocab"]),
                            "fear": "", "source": "operators/arcs_lte.py:" + key.value})
            return out
    raise SystemExit("ARCHETYPE_REGISTRY not found in operators/arcs_lte.py")


def operators():
    ops = json.loads((ROOT / "operators/OPERATOR-REGISTRY.json").read_text())["operators"]
    # kind "derive": a full listener profile is derived at run time by Claude from this line (Zach,
    # 2026-11-16: operators get full profiles like the archetypes), shown and labelled unchecked.
    return [{"id": "op-%d" % o["op"], "family": "operator", "kind": "derive", "name": "%d %s" % (o["op"], o["name"]),
             "seed": "Operator %d %s, role %s, function: %s (periodic-table level: %s)" % (o["op"], o["name"], o["role"], o["function"], o["level"]),
             "source": "operators/OPERATOR-REGISTRY.json op %d" % o["op"]} for o in ops]


def primitives():
    text = (ROOT / "CLAUDE.md").read_text()
    block = text.split("## ROM Primitives", 1)[1].split("\n## ", 1)[0]
    out = []
    for n, name, body in re.findall(r"^(\d)\. \*\*(.+?)\*\* [—-] (.+)$", block, re.M):
        out.append({"id": "rom-" + n, "family": "primitive", "kind": "lens", "name": name.title(),
                    "lens": "%s: %s" % (name, body.strip()), "source": "CLAUDE.md ROM primitive " + n})
    if len(out) != 7:
        raise SystemExit("expected 7 ROM primitives in CLAUDE.md, found %d" % len(out))
    return out


def advisors():
    out = []
    files = sorted((ROOT / ".claude/agents").glob("chief-*.md")) + sorted((ROOT / ".claude/agents").glob("idea-*.md"))
    files += [ROOT / ".claude/agents" / f for f in ("grug.md", "scenario-runner.md")]
    for f in files:
        m = re.search(r"^description:\s*\"?(.+?)\"?\s*$", f.read_text(), re.M)
        desc = re.sub(r"^\[CANDIDATE\]\s*", "", m.group(1)) if m else ""
        out.append({"id": "adv-" + f.stem, "family": "advisor", "kind": "audience", "name": f.stem,
                    "dialect": desc, "entry": "Answer the job in its description first.", "revealed": desc,
                    "avoid": "Padding, praise, claims it cannot check.", "fear": "",
                    "source": ".claude/agents/" + f.name})
    return out


def block():
    reg = {"archetype": archetypes(), "advisor": advisors(), "operator": operators(), "primitive": primitives(),
           "gaps": ["protocol: no registry of protocols exists in the repo, so none are loaded"]}
    return BEGIN + "\nvar REGISTRY = " + json.dumps(reg, ensure_ascii=False, separators=(",", ":")) + ";\n" + END


def main():
    page = PAGE.read_text()
    i, j = page.find(BEGIN), page.find(END)
    if i < 0 or j < 0:
        raise SystemExit("registry markers not found in " + str(PAGE.relative_to(ROOT)))
    new = page[:i] + block() + page[j + len(END):]
    if "--check" in sys.argv:
        if new != page:
            print("babel_fish_listeners: page registry is stale; run python3 scripts/babel_fish_listeners.py")
            return 1
        print("babel_fish_listeners: page registry up to date")
        return 0
    PAGE.write_text(new)
    print("babel_fish_listeners: wrote registry into", PAGE.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
