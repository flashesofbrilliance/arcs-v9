#!/usr/bin/env python3
"""release_notes: what actually landed on main, grouped by week and area, from git alone.

Why: there is no CHANGELOG. The night-moves digests, handoff blocks and decision receipts each
hold part of the story, and a belief like "we rewired the compass backend" had nothing to be
checked against. This reads the first-parent history of origin/main (merge commits of PRs, plus
direct commits), classifies each change by the files it touched, and prints notes you can grep.

Area is derived from FILES TOUCHED, never from the title, so a title cannot claim an area the
diff did not change. When a change touches both code and docs, the code decides.

  python3 scripts/release_notes.py --since 2026-09-15            # to stdout
  python3 scripts/release_notes.py --since 2026-09-15 --write    # _RELEASES/<until>.md
  python3 scripts/release_notes.py --self-test

Reads: git log and git diff only. Writes: only with --write. Stdlib only.
"""
import argparse, collections, datetime as dt, os, re, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
REF = "origin/main"

# Ordered: first match wins. (area, regex on repo-relative path)
RULES = [
    ("compass", r"^src/app/api/compass/|^src/lib/(ygate|compass-response|claude-models|model-error|model-error-codes|horizon|request-schemas|session-owner|mockCompass)\.|^src/app/dashboard/"),
    ("operators", r"^operators/|^scripts/(arcs_core|arcs_cli|lattice_sim|arcs_models|operator_registry_emit|echo_ridgeline_feed|score_me)\.py$"),
    ("receipts+brief", r"^src/app/api/(receipts|brief|guide|history|prep|save)|^src/app/(brief|receipt)|^src/lib/(brief|receipt)|^prisma/"),
    ("surfaces", r"^public/|^src/app/|^src/components/|^src/ui-kit/|^next\.config"),
    ("ci+tooling", r"^\.github/|^scripts/|^\.claude/|^tests/|^package(-lock)?\.json$"),
    ("docs+records", r"^_|\.md$|^runtime/|^tools/"),
]
CODE_AREAS = {"compass", "operators", "receipts+brief", "surfaces", "ci+tooling"}
ORDER = ["compass", "operators", "receipts+brief", "surfaces", "ci+tooling", "docs+records", "other"]


def classify_file(path):
    for area, rx in RULES:
        if re.search(rx, path):
            return area
    return "other"


def classify(paths):
    """Majority area among files; code areas outrank docs when both are present."""
    areas = [classify_file(p) for p in paths]
    code = [a for a in areas if a in CODE_AREAS]
    pool = code or areas
    if not pool:
        return "other"
    counts = collections.Counter(pool)
    best = max(counts.values())
    for a in ORDER:  # deterministic tie-break
        if counts.get(a) == best:
            return a
    return "other"


def git(*args):
    return subprocess.run(["git", "-C", ROOT, *args], capture_output=True, text=True, check=True).stdout


def clean_title(t):
    t = re.sub(r"\s*\[NCI:[^\]]*\]\s*$", "", t.strip())
    return t


def entries(since, until):
    fmt = "%H%x1f%ad%x1f%P%x1f%s%x1f%b%x1e"
    raw = git("log", "--first-parent", f"--since={since}", f"--until={until} 23:59:59",
              "--date=short", f"--format={fmt}", REF)
    out = []
    for rec in raw.split("\x1e"):
        rec = rec.strip("\n")
        if not rec:
            continue
        sha, date, parents, subj, body = (rec.split("\x1f") + [""] * 5)[:5]
        parents = parents.split()
        m = re.match(r"Merge pull request #(\d+) ", subj)
        if len(parents) > 1:
            if not m:
                continue  # branch-sync merges carry no change of their own
            title = next((l for l in body.splitlines() if l.strip()), subj)
            pr = int(m.group(1))
            files = git("diff", "--name-only", parents[0], sha).split()
        else:
            title, pr = subj, None
            files = git("diff-tree", "--no-commit-id", "--name-only", "-r", sha).split()
        out.append({"sha": sha[:8], "date": date, "pr": pr, "title": clean_title(title),
                    "area": classify(files), "nfiles": len(files)})
    return out


def week_of(date):
    y, w, _ = dt.date.fromisoformat(date).isocalendar()
    return f"{y}-W{w:02d}"


def render(es, since, until):
    lines = [f"# Release notes {since} to {until}", "",
             f"{len(es)} changes on main ({sum(1 for e in es if e['pr'])} merged PRs, "
             f"{sum(1 for e in es if not e['pr'])} direct commits). Generated by scripts/release_notes.py "
             f"from `{REF}` first-parent history.", "",
             "Area comes from the files a change touched, not its title; when code and docs both changed, "
             "code decides. Titles are the authors' own words. This lists what merged, not whether it "
             "works in production. For that, see the decision receipts.", ""]
    totals = collections.Counter(e["area"] for e in es)
    lines.append("Totals by area: " + ", ".join(f"{a} {totals[a]}" for a in ORDER if totals[a]) + ".")
    lines.append("")
    by_week = collections.defaultdict(list)
    for e in es:
        by_week[week_of(e["date"])].append(e)
    for wk in sorted(by_week, reverse=True):
        lines += [f"## {wk}", ""]
        by_area = collections.defaultdict(list)
        for e in by_week[wk]:
            by_area[e["area"]].append(e)
        for a in ORDER:
            if not by_area[a]:
                continue
            lines.append(f"### {a}")
            for e in by_area[a]:
                ref = f"#{e['pr']}, " if e["pr"] else ""
                lines.append(f"- {e['title']} ({ref}{e['sha']}, {e['date']})")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def self_test():
    cases = [
        (["src/app/api/compass/route.ts"], "compass"),
        (["src/app/api/compass/route.ts", "CLAUDE.md", "_STATE/x.md"], "compass"),
        (["operators/arcs_accountant.py", "_STATE/y.json"], "operators"),
        (["_DECISIONS/ADR-1.md", "CLAUDE.md"], "docs+records"),
        (["public/status.html"], "surfaces"),
        (["scripts/merge_train.sh", ".github/workflows/ci.yml"], "ci+tooling"),
        (["src/app/api/receipts/route.ts"], "receipts+brief"),
        ([], "other"),
    ]
    bad = [(p, want, classify(p)) for p, want in cases if classify(p) != want]
    # the fail-on-bad half: a docs-titled change that touched compass code must say compass
    assert classify(["docs/x.md", "src/lib/ygate.ts"]) == "compass"
    if bad:
        print("FAIL", bad)
        return 1
    print("release_notes self-test: ok")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--since", default=(dt.date.today() - dt.timedelta(days=14)).isoformat())
    ap.add_argument("--until", default=dt.date.today().isoformat())
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    text = render(entries(a.since, a.until), a.since, a.until)
    if a.write:
        d = os.path.join(ROOT, "_RELEASES")
        os.makedirs(d, exist_ok=True)
        p = os.path.join(d, f"{a.until}.md")
        open(p, "w").write(text)
        print(p)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
